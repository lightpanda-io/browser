#!/usr/bin/env bash
set -euo pipefail

cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}"

ACTION=.github/actions/install/action.yml
OUT=nix/v8-deps.nix

V8_VERSION=$(awk -F\' '/^  v8:/{f=1} f&&/default:/{print $2; exit}' "$ACTION")
ZIG_V8_TAG=$(awk -F\' '/^  zig-v8:/{f=1} f&&/default:/{print $2; exit}' "$ACTION")

declare -A PLATFORMS=(
  [aarch64-linux]=linux_aarch64
  [x86_64-linux]=linux_x86_64
)

echo "v8 ${V8_VERSION} @ ${ZIG_V8_TAG}"

workdir=$(mktemp -d)
trap 'rm -rf "$workdir"' EXIT

fetch_one() {
  local system="$1" platform="$2"
  local url="https://github.com/lightpanda-io/zig-v8-fork/releases/download/${ZIG_V8_TAG}/libc_v8_${V8_VERSION}_${platform}.a"
  local tmp="$workdir/$system.a"
  echo "  fetching ${system} (${platform})..." >&2
  curl -fsSL "$url" -o "$tmp"
  local sha256 hash
  sha256=$(sha256sum "$tmp" | cut -d' ' -f1)
  hash=$(nix hash convert --hash-algo sha256 --to sri "$sha256")
  rm -f "$tmp"
  {
    echo "    ${system} = {"
    echo "      platform = \"${platform}\";"
    echo "      hash = \"${hash}\";"
    echo "    };"
  } > "$workdir/$system.nix"
}

pids=()
for system in "${!PLATFORMS[@]}"; do
  fetch_one "$system" "${PLATFORMS[$system]}" &
  pids+=("$!")
done
for pid in "${pids[@]}"; do
  wait "$pid"
done

{
  echo "# Generated by nix/update-v8-deps.sh — do not edit by hand."
  echo "{"
  echo "  version = \"${V8_VERSION}\";"
  echo "  tag = \"${ZIG_V8_TAG}\";"
  echo "  archives = {"
  for system in "${!PLATFORMS[@]}"; do
    cat "$workdir/$system.nix"
  done
  echo "  };"
  echo "}"
} > "$OUT"

echo "wrote ${OUT}"
