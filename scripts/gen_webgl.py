"""Generates src/browser/webapi/canvas/WebGL{,2}RenderingContext.zig from
the WebGL IDL that WPT keeps (interfaces/webgl1.idl and webgl2.idl).

    uv run python scripts/gen_webgl.py ../wpt/interfaces src/browser/webapi/canvas

Methods that return nothing become noops; the others map to webgl.zig.
"""
import re, sys

def blocks(text):
    out = {}
    for m in re.finditer(r'interface\s+(?:mixin\s+)?(\w+)[^{]*\{(.*?)\n\};', text, re.S):
        out[m.group(1)] = m.group(2)
    return out
def members(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    consts, methods, attrs = [], {}, []
    for stmt in body.split(';'):
        s = ' '.join(stmt.split())
        if not s: continue
        s = re.sub(r'^\[[^\]]*\]\s*', '', s)
        if s.startswith('const '):
            m = re.match(r'const \w+ (\w+) = (0x[0-9A-Fa-f]+|-?\d+)', s); consts.append((m.group(1), m.group(2)))
        elif 'attribute' in s:
            attrs.append(s)
        else:
            m = re.match(r'(.+?)\s+(\w+)\((.*)\)$', s)
            if m: methods.setdefault(m.group(2), []).append({'ret': m.group(1), 'args': m.group(3)})
    return consts, methods, attrs

idl_dir, out = sys.argv[1], sys.argv[2]
b = {**blocks(open(f'{idl_dir}/webgl1.idl').read()), **blocks(open(f'{idl_dir}/webgl2.idl').read())}
d = {}
for name, text in b.items():
    c, m, a = members(text)
    d[name] = {'consts': c, 'methods': m}

VALUE = {
    'getContextAttributes': 'getContextAttributes', 'isContextLost': 'isContextLost',
    'getSupportedExtensions': 'getSupportedExtensions', 'getExtension': 'getExtension',
    'checkFramebufferStatus': 'checkFramebufferStatus', 'getParameter': 'getParameter',
    'getError': 'getError', 'isEnabled': 'isEnabled',
    'getShaderParameter': 'getShaderParameter', 'getProgramParameter': 'getProgramParameter',
    'getShaderPrecisionFormat': 'getShaderPrecisionFormat', 'getVertexAttrib': 'getVertexAttrib',
    'getInternalformatParameter': 'getInternalformatParameter', 'getQueryParameter': 'getQueryParameter',
    'getSyncParameter': 'getSyncParameter', 'clientWaitSync': 'clientWaitSync',
    'getUniformLocation': 'getUniformLocation', 'fenceSync': 'fenceSync',
    'getActiveAttrib': 'none', 'getActiveUniform': 'none', 'getTransformFeedbackVarying': 'none',
    'getQuery': 'none', 'getIndexedParameter': 'none',
    'getAttachedShaders': 'emptyList', 'getUniformIndices': 'emptyList', 'getActiveUniforms': 'emptyList',
    'getProgramInfoLog': 'emptyString', 'getShaderInfoLog': 'emptyString', 'getShaderSource': 'emptyString',
    'getActiveUniformBlockName': 'emptyString',
    'getAttribLocation': 'zero', 'getFragDataLocation': 'zero', 'getUniformBlockIndex': 'zero',
    'getVertexAttribOffset': 'zero', 'getBufferParameter': 'zero', 'getRenderbufferParameter': 'zero',
    'getTexParameter': 'zero', 'getFramebufferAttachmentParameter': 'zero', 'getUniform': 'zero',
    'getSamplerParameter': 'zero', 'getActiveUniformBlockParameter': 'zero',
}
for n in ['Buffer', 'Framebuffer', 'Program', 'Renderbuffer', 'Shader', 'Texture', 'Query', 'Sampler', 'TransformFeedback', 'VertexArray']:
    VALUE['create' + n] = 'create' + n
for n in ['Buffer', 'Framebuffer', 'Program', 'Renderbuffer', 'Shader', 'Texture', 'Query', 'Sampler', 'Sync', 'TransformFeedback', 'VertexArray']:
    VALUE['is' + n] = 'isObject'

HEADER = ''.join(open(f'{out}/webgl.zig').readlines()[:17])

def emit(cls, version, ifaces, extra_register):
    consts, methods = {}, {}
    for i in ifaces:
        for n, v in d[i]['consts']: consts.setdefault(n, v)
        for n, ov in d[i]['methods'].items(): methods.setdefault(n, ov)
    lines = [HEADER.rstrip(), '',
             f'// Generated by scripts/gen_webgl.py from the WebGL IDL (wpt/interfaces/webgl{1 if version == "webgl1" else "1 and webgl2"}.idl).',
             '// The methods are in webgl.zig.', '',
             'const lp = @import("lightpanda");', '',
             'const webgl = @import("webgl.zig");', 'const Canvas = @import("../element/html/Canvas.zig");', '',
             'const js = lp.js;', '',
             f'const {cls} = @This();', '', '_canvas: *Canvas,', '']
    if extra_register:
        lines += ['pub fn registerTypes() []const type {', f'    return &([_]type{{{cls}}} ++ webgl.object_types);', '}', '']
    lines += [f'const M = webgl.Methods({cls}, .{version});', '',
              'pub const JsApi = struct {', f'    pub const bridge = js.Bridge({cls});', '',
              '    pub const Meta = struct {', f'        pub const name = "{cls}";', '',
              '        pub var class_id: bridge.ClassId = undefined;', '    };', '',
              '    pub const canvas = bridge.accessor(M.getCanvas, null, .{});',
              '    pub const drawingBufferWidth = bridge.accessor(M.getDrawingBufferWidth, null, .{});',
              '    pub const drawingBufferHeight = bridge.accessor(M.getDrawingBufferHeight, null, .{});',
              '    pub const drawingBufferFormat = bridge.accessor(M.getDrawingBufferFormat, null, .{});',
              '    pub const drawingBufferColorSpace = bridge.accessor(M.getColorSpace, M.setColorSpace, .{});',
              '    pub const unpackColorSpace = bridge.accessor(M.getColorSpace, M.setColorSpace, .{});', '']
    for n, v in consts.items():
        lines.append(f'    pub const {n} = bridge.property({v}, .{{ .template = true }});')
    lines.append('')
    unknown = []
    for n in sorted(methods):
        rets = {o['ret'] for o in methods[n]}
        if rets == {'undefined'}:
            lines.append(f'    pub const {n} = bridge.function(M.noop, .{{ .noop = true }});')
        elif n in VALUE:
            lines.append(f'    pub const {n} = bridge.function(M.{VALUE[n]}, .{{}});')
        else:
            unknown.append((n, rets))
    if unknown:
        sys.exit(f'{cls}: no value method for {unknown}')
    lines += ['};', '']
    open(f'{out}/{cls}.zig', 'w').write('\n'.join(lines))
    print(cls, len(consts), 'constants', len(methods), 'methods')

emit('WebGLRenderingContext', 'webgl1', ['WebGLRenderingContextBase', 'WebGLRenderingContextOverloads'], True)
emit('WebGL2RenderingContext', 'webgl2', ['WebGLRenderingContextBase', 'WebGL2RenderingContextBase', 'WebGL2RenderingContextOverloads'], False)
