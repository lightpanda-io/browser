"""Generates src/browser/webapi/canvas/WebGL{,2}RenderingContext.zig from
the WebGL IDL that WPT keeps (interfaces/webgl1.idl and webgl2.idl).

    uv run python scripts/gen_webgl.py ../wpt/interfaces src/browser/webapi/canvas

Methods that return nothing become noops; the others map to webgl.zig.
"""
import re, sys


def interfaces(text):
    return dict(re.findall(r'interface\s+(?:mixin\s+)?(\w+)[^{]*\{(.*?)\n\};', text, re.S))


def members(body):
    """The constants, and each method's return types (one per overload)."""
    body = re.sub(r'/\*.*?\*/|//[^\n]*', '', body, flags=re.S)
    consts, methods = {}, {}
    for stmt in body.split(';'):
        s = re.sub(r'^\[[^\]]*\]\s*', '', ' '.join(stmt.split()))
        if m := re.match(r'const \w+ (\w+) = (0x[0-9A-Fa-f]+|-?\d+)', s):
            consts[m.group(1)] = m.group(2)
        elif 'attribute' not in s and (m := re.match(r'(.+?)\s+(\w+)\(.*\)$', s)):
            methods.setdefault(m.group(2), set()).add(m.group(1))
    return consts, methods


idl_dir, out = sys.argv[1], sys.argv[2]
idl = {name: members(body) for f in ('webgl1', 'webgl2') for name, body in interfaces(open(f'{idl_dir}/{f}.idl').read()).items()}
webgl_zig = open(f'{out}/webgl.zig').read()
HEADER = ''.join(webgl_zig.splitlines(True)[:17])

CREATES = {
    'createBuffer': 'WebGLBuffer', 'createFramebuffer': 'WebGLFramebuffer', 'createProgram': 'WebGLProgram',
    'createRenderbuffer': 'WebGLRenderbuffer', 'createShader': 'WebGLShader', 'createTexture': 'WebGLTexture',
    'createQuery': 'WebGLQuery', 'createSampler': 'WebGLSampler', 'createTransformFeedback': 'WebGLTransformFeedback',
    'createVertexArray': 'WebGLVertexArrayObject', 'fenceSync': 'WebGLSync', 'getUniformLocation': 'WebGLUniformLocation',
}

# Value methods that share one of webgl.zig's generic ones. The rest are
# implemented under their own name.
SHARED = {
    'isContextLost': 'no', 'isEnabled': 'no', 'getExtension': 'none',
    'getActiveAttrib': 'none', 'getActiveUniform': 'none', 'getTransformFeedbackVarying': 'none',
    'getQuery': 'none', 'getIndexedParameter': 'none',
    'getSupportedExtensions': 'emptyList', 'getAttachedShaders': 'emptyList',
    'getUniformIndices': 'emptyList', 'getActiveUniforms': 'emptyList',
    'getProgramInfoLog': 'emptyString', 'getShaderInfoLog': 'emptyString', 'getShaderSource': 'emptyString',
    'getActiveUniformBlockName': 'emptyString',
    'getError': 'zero', 'getAttribLocation': 'zero', 'getFragDataLocation': 'zero', 'getUniformBlockIndex': 'zero',
    'getVertexAttribOffset': 'zero', 'getBufferParameter': 'zero', 'getRenderbufferParameter': 'zero',
    'getTexParameter': 'zero', 'getFramebufferAttachmentParameter': 'zero', 'getUniform': 'zero',
    'getSamplerParameter': 'zero', 'getActiveUniformBlockParameter': 'zero',
}


def value_method(name):
    if name in CREATES:
        return f'M.create(webgl.{CREATES[name]})'
    fn = SHARED.get(name) or ('isObject' if name.startswith('is') else name)
    if not re.search(rf'pub fn {fn}\(', webgl_zig):
        sys.exit(f'webgl.zig has no {fn} for {name}')
    return f'M.{fn}'


def emit(cls, version, ifaces):
    consts, methods = {}, {}
    for i in ifaces:
        for n, v in idl[i][0].items():
            consts.setdefault(n, v)
        for n, rets in idl[i][1].items():
            methods.setdefault(n, set()).update(rets)
    idls = 'webgl1.idl' if version == 'webgl1' else 'webgl1.idl and webgl2.idl'
    lines = [HEADER.rstrip(), '',
             f'// Generated by scripts/gen_webgl.py from wpt/interfaces/{idls}.',
             '// The methods are in webgl.zig.', '',
             'const lp = @import("lightpanda");', '',
             'const webgl = @import("webgl.zig");', 'const Canvas = @import("../element/html/Canvas.zig");', '',
             'const js = lp.js;', '',
             f'const {cls} = @This();', '', '_canvas: *Canvas,', '']
    if version == 'webgl1':
        lines += ['pub fn registerTypes() []const type {', f'    return &([_]type{{{cls}}} ++ webgl.object_types);', '}', '']
    lines += [f'const M = webgl.Methods({cls}, .{version});', '',
              'pub const JsApi = struct {', f'    pub const bridge = js.Bridge({cls});', '',
              '    pub const Meta = struct {', f'        pub const name = "{cls}";', '',
              '        pub var class_id: bridge.ClassId = undefined;', '    };', '',
              '    pub const canvas = bridge.accessor(M.getCanvas, null, .{});',
              '    pub const drawingBufferWidth = bridge.accessor(M.getDrawingBufferWidth, null, .{});',
              '    pub const drawingBufferHeight = bridge.accessor(M.getDrawingBufferHeight, null, .{});',
              '    pub const drawingBufferFormat = bridge.accessor(M.getDrawingBufferFormat, null, .{});',
              '    pub const drawingBufferColorSpace = bridge.accessor(M.getColorSpace, M.setColorSpace, .{});',
              '    pub const unpackColorSpace = bridge.accessor(M.getColorSpace, M.setColorSpace, .{});', '']
    lines += [f'    pub const {n} = bridge.property({v}, .{{ .template = true }});' for n, v in consts.items()]
    lines.append('')
    for n in sorted(methods):
        if methods[n] == {'undefined'}:
            lines.append(f'    pub const {n} = bridge.function(M.noop, .{{ .noop = true }});')
        else:
            lines.append(f'    pub const {n} = bridge.function({value_method(n)}, .{{}});')
    lines += ['};', '']
    open(f'{out}/{cls}.zig', 'w').write('\n'.join(lines))
    print(cls, len(consts), 'constants', len(methods), 'methods')


emit('WebGLRenderingContext', 'webgl1', ['WebGLRenderingContextBase', 'WebGLRenderingContextOverloads'])
emit('WebGL2RenderingContext', 'webgl2', ['WebGLRenderingContextBase', 'WebGL2RenderingContextBase', 'WebGL2RenderingContextOverloads'])
